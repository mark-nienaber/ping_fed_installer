#!/bin/bash
set -euo pipefail

################################################################################
# Script Name: setup_loadbalancer.sh
# Description: Stand up the front-door load balancer (HAProxy) that TERMINATES
#              client TLS on :443 and routes by Host/SNI to the clustered
#              runtime tiers, re-encrypting to the HTTPS backends (TLS bridging):
#
#                 https://ping.<domain>  -> PingFederate engine node(s)  :9032
#                 https://app.<domain>   -> PingAccess engine            :3000
#
#              This is the textbook front for a PingFederate engine cluster: the
#              OIDC issuer becomes the LB URL and engines scale behind it. Add
#              more `server` lines to the pf_engine backend as engines are added.
#
#   - Self-signed cert with a SAN covering both front-door hostnames.
#   - SELinux: allow HAProxy to connect to the backend ports.
#   Idempotent: regenerates config each run; only issues the cert if absent.
################################################################################

source ./pingconfig.env
_LIB_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/../lib" && pwd)"
# shellcheck disable=SC1091
source "${_LIB_DIR}/logging.sh"

CERT_DIR="/etc/haproxy/certs"
PEM="${CERT_DIR}/lb.pem"
CFG="/etc/haproxy/haproxy.cfg"

trap 'error "setup_loadbalancer.sh failed at line $LINENO"' ERR

function need_haproxy() {
    command -v haproxy >/dev/null || { error "haproxy not installed (dnf install haproxy)"; return 1; }
    success "haproxy: $(haproxy -v 2>/dev/null | head -1)"
}

# Both front-door hostnames must resolve (to this host, single-node demo).
function ensure_hosts() {
    for h in "$LB_HOSTNAME_PF" "$LB_HOSTNAME_APP"; do
        if ! getent hosts "$h" >/dev/null 2>&1; then
            info "Adding ${h} -> 127.0.0.1 to /etc/hosts"
            echo "127.0.0.1  ${h}" | sudo tee -a /etc/hosts >/dev/null
        fi
    done
    success "Front-door hostnames resolve"
}

function issue_cert() {
    if sudo test -f "$PEM"; then success "LB certificate already present"; return 0; fi
    info "Issuing self-signed LB cert (SAN: ${LB_HOSTNAME_PF}, ${LB_HOSTNAME_APP})..."
    sudo mkdir -p "$CERT_DIR"
    local tmp; tmp=$(mktemp -d)
    openssl req -x509 -newkey rsa:2048 -nodes \
        -keyout "${tmp}/lb.key" -out "${tmp}/lb.crt" -days 825 \
        -subj "/CN=${LB_HOSTNAME_PF}" \
        -addext "subjectAltName=DNS:${LB_HOSTNAME_PF},DNS:${LB_HOSTNAME_APP}" >/dev/null 2>&1
    cat "${tmp}/lb.crt" "${tmp}/lb.key" > "${tmp}/lb.pem"
    sudo cp "${tmp}/lb.pem" "$PEM"
    sudo chmod 640 "$PEM"; sudo chown root:haproxy "$PEM" 2>/dev/null || true
    rm -rf "$tmp"
    success "LB cert issued -> ${PEM}"
}

function selinux_allow() {
    if command -v getenforce >/dev/null && [[ "$(getenforce)" == "Enforcing" ]]; then
        info "SELinux enforcing — allowing HAProxy to connect to backend ports..."
        sudo setsebool -P haproxy_connect_any 1
        success "haproxy_connect_any enabled"
    fi
}

function write_config() {
    info "Writing ${CFG}..."
    local tmp; tmp=$(mktemp)
    cat > "$tmp" <<CFG
#-----------------------------------------------------------------------
# Front-door load balancer for the Ping stack (generated by
# setup_loadbalancer.sh). Terminates client TLS on :${LB_HTTPS_PORT} and
# routes by Host to the clustered runtime tiers, re-encrypting to backends.
#-----------------------------------------------------------------------
global
    log /dev/log local0
    maxconn 4096
    tune.ssl.default-dh-param 2048
    user haproxy
    group haproxy
    daemon

defaults
    mode http
    log global
    option httplog
    option forwardfor
    option http-server-close
    timeout connect 10s
    timeout client  60s
    timeout server  60s

frontend https_in
    bind :${LB_HTTPS_PORT} ssl crt ${PEM}
    http-request set-header X-Forwarded-Proto https
    http-request set-header X-Forwarded-Port  ${LB_HTTPS_PORT}
    # Route by Host header (client SNI). Match with or without :443.
    acl is_pf  hdr(host) -i ${LB_HOSTNAME_PF}  ${LB_HOSTNAME_PF}:${LB_HTTPS_PORT}
    acl is_app hdr(host) -i ${LB_HOSTNAME_APP} ${LB_HOSTNAME_APP}:${LB_HTTPS_PORT}
    use_backend pf_engine if is_pf
    use_backend pa_engine if is_app
    default_backend pa_engine

# PingFederate engine cluster (OIDC runtime). Add engine nodes here as the
# cluster scales; the LB URL is the OIDC issuer.
backend pf_engine
    balance roundrobin
    # Health check over TLS (check-ssl) with a Host header — PF/Jetty 400s a
    # check request that has no Host.
    option httpchk
    http-check send meth GET uri /pf/heartbeat.ping hdr Host ${LB_HOSTNAME_PF}
    http-check expect status 200
    server pf-engine-2 127.0.0.1:${PINGFED2_ENGINE_PORT} ssl verify none check check-ssl

# PingAccess engine (app enforcement point).
backend pa_engine
    balance roundrobin
    server pa-engine-1 127.0.0.1:${PINGACCESS_ENGINE_PORT} ssl verify none check
CFG
    sudo cp "$tmp" "$CFG"; rm -f "$tmp"
    success "Config written"
}

function validate_and_start() {
    info "Validating HAProxy config..."
    sudo haproxy -c -f "$CFG" >/dev/null 2>&1 || { error "haproxy config invalid"; sudo haproxy -c -f "$CFG"; return 1; }
    success "Config valid"
    info "Starting HAProxy..."
    sudo systemctl enable haproxy >/dev/null 2>&1 || true
    sudo systemctl restart haproxy
    local i=0
    while [[ $i -lt 15 ]]; do
        ss -ltn 2>/dev/null | grep -q ":${LB_HTTPS_PORT} " && { success "HAProxy listening on :${LB_HTTPS_PORT}"; return 0; }
        sleep 2; ((i++)) || true
    done
    error "HAProxy not listening on :${LB_HTTPS_PORT} (systemctl status haproxy)"; return 1
}

# -----------------------------------------------------------------------------
section "Load balancer — HAProxy (TLS termination)"
if [[ "${LB_ENABLED:-false}" != "true" ]]; then
    info "LB_ENABLED=${LB_ENABLED:-false} — skipping load balancer"; exit 0
fi
need_haproxy
ensure_hosts
issue_cert
selinux_allow
write_config
validate_and_start
success "Load balancer ready: https://${LB_HOSTNAME_PF} -> PF engine, https://${LB_HOSTNAME_APP} -> PA engine"
